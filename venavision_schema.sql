-- VenaVein database schema
-- Clean schema-only version. Run as a PostgreSQL database owner/superuser.

BEGIN;

CREATE TABLE public.departments (
    department_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_name varchar(100) NOT NULL UNIQUE,
    hospital_name varchar(150),
    location varchar(100)
);

CREATE TABLE public.devices (
    device_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_name varchar(100) NOT NULL,
    device_type varchar(100),
    serial_number varchar(100) UNIQUE,
    status varchar(30) DEFAULT 'inactive',
    created_at timestamptz DEFAULT now(),
    battery_level integer CHECK (battery_level BETWEEN 0 AND 100),
    last_seen timestamp,
    firmware_version varchar(30)
);

CREATE TABLE public.device_logs (
    log_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id integer REFERENCES public.devices(device_id),
    log_time timestamp DEFAULT CURRENT_TIMESTAMP,
    log_level varchar(20),
    message text,
    event_type varchar(50),
    resolved boolean DEFAULT false
);

CREATE TABLE public.patients (
    id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    first_name text NOT NULL,
    last_name text NOT NULL,
    birth_date date NOT NULL,
    diagnose text NOT NULL,
    last_prick date NOT NULL,
    blood_type varchar(3),
    sex text CHECK (sex IN ('Female', 'Male')),
    follow_up date NOT NULL,
    cpr_number varchar(11),
    notes text,
    source text NOT NULL DEFAULT 'Manuel'
        CHECK (source IN ('Manuel', 'Script'))
);

CREATE TABLE public.staff (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    specialty text,
    department_id integer REFERENCES public.departments(department_id),
    job_title varchar(100)
);

CREATE TABLE public.visits (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id integer NOT NULL
        REFERENCES public.patients(id) ON DELETE CASCADE,
    staff_id integer REFERENCES public.staff(id),
    visit_time timestamp NOT NULL,
    notes text,
    source text NOT NULL DEFAULT 'manuel'
        CHECK (source IN ('manuel', 'generator'))
);

CREATE TABLE public.scans (
    scan_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visit_id integer NOT NULL REFERENCES public.visits(id),
    device_id integer REFERENCES public.devices(device_id),
    scan_time timestamptz DEFAULT now(),
    vein_detected boolean,
    marking_completed boolean DEFAULT false,
    image_path text,
    notes text,
    scan_duration_ms integer,
    confidence_score numeric(5,2),
    error_message text
);

CREATE INDEX idx_visits_patient ON public.visits(patient_id);

CREATE VIEW public.device_error_log AS
SELECT
    l.log_id,
    d.device_name,
    l.log_time,
    l.log_level,
    l.event_type,
    l.message,
    l.resolved
FROM public.device_logs AS l
JOIN public.devices AS d ON d.device_id = l.device_id
WHERE l.log_level = 'ERROR';

CREATE VIEW public.device_status AS
SELECT
    device_id,
    device_name,
    device_type,
    serial_number,
    status,
    battery_level,
    last_seen,
    firmware_version
FROM public.devices;

CREATE VIEW public.scan_history AS
SELECT
    s.scan_id,
    p.id AS patient_id,
    p.first_name,
    p.last_name,
    v.visit_time,
    d.device_name,
    s.scan_time,
    s.vein_detected,
    s.marking_completed,
    s.scan_duration_ms,
    s.confidence_score
FROM public.scans AS s
JOIN public.visits AS v ON v.id = s.visit_id
JOIN public.patients AS p ON p.id = v.patient_id
JOIN public.devices AS d ON d.device_id = s.device_id;
COMMIT;
